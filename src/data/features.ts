export function featuresOf(group: GroupId): Feature[] {
  return FEATURES.filter((item) => item.group === group);
}

export function feature(id: string): Feature {
  const found = FEATURES.find((item) => item.id === id);
  if (!found) throw new Error(`Unknown feature "${id}"`);
  return found;
}

